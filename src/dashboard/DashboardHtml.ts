export interface DashboardHtmlOptions {
  cspSource: string;
  nonce: string;
}

// [CUSTOM-230 Dashboard 页面上的按钮 === 这份白名单，两边一一对应（spec 钉住）：
// 页面里能点的命令只能是这里列出的。**两条都不在这里**：
// · `vac.refreshDashboard` —— 刷新在视图标题栏那颗 ⭯（view/title 的 `when: view == vac-dashboard`），
//   而面板每次可见又会自己 refresh（`DashboardViewProvider.setVisible`），页面里再放一颗就是第三个入口；
// · `vac.openChatInEditor` —— 它的入口是**标题栏 ↻ 左侧那颗图标**（`package.json` 的 view/title，
//   与 Agents 面板同一颗），页面上不再放第二颗（用户 2026-10-13 确认）。
export const DASHBOARD_COMMANDS = ['vac.newConversation', 'vac.connectAgent'] as const;

const CLIENT_SCRIPT = [
  '(function () {',
  "  var api = acquireVsCodeApi();",
  "  var COMMANDS = ['vac.newConversation','vac.connectAgent'];",
  '  function slot(id) { return document.getElementById(id); }',
  "  function esc(s) { return String(s === null || s === undefined ? '' : s).replace(/[&<>\"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '\"': '&quot;', \"'\": '&#39;' }[c]; }); }",
  "  function tok(n) { n = n || 0; if (n >= 1e9) { return (n / 1e9).toFixed(2) + 'B'; } if (n >= 1e6) { return (n / 1e6).toFixed(2) + 'M'; } if (n >= 1e3) { return (n / 1e3).toFixed(1) + 'k'; } return String(n); }",
  "  function cost(c) { return '$' + (c || 0).toFixed(2); }",
  '  var EST_TIP = "Estimated equivalent API cost: what these tokens would cost at list API prices. Not an amount billed to a subscription.";',
  '  function card(title, p, note) {',
  "    return '<div class=\"card\"><div class=\"cap\">' + esc(title) + '</div>' +",
  "      '<div class=\"big\">' + tok(p.tokens) + ' <span class=\"dim\">tokens</span></div>' +",
  "      '<div class=\"dim\">in ' + tok(p.input) + ' \\u00b7 out ' + tok(p.output) + '</div>' +",
  "      '<div class=\"dim\">cache write ' + tok(p.cacheCreate) + ' \\u00b7 read ' + tok(p.cacheRead) + '</div>' +",
  "      '<div class=\"cost\" title=\"' + esc(EST_TIP) + '\">est. ' + cost(p.cost) + (note ? ' <span class=\"dim\">' + esc(note) + '</span>' : '') + '</div></div>';",
  '  }',
  '  function chart(daily) {',
  '    var n = daily.length; var max = 0; var total = 0; var i;',
  '    for (i = 0; i < n; i++) { total += daily[i].tokens; if (daily[i].tokens > max) { max = daily[i].tokens; } }',
  "    var w = 300; var h = 56; var bw = w / n; var out = ['<svg viewBox=\"0 0 ' + w + ' ' + h + '\" width=\"100%\" height=\"56\" preserveAspectRatio=\"none\" role=\"img\">',",
  '      "<title>Tokens per day, last 30 days</title>",',
  '      \'<desc>\' + esc(tok(total) + " tokens across 30 days; peak day " + tok(max)) + \'</desc>\'];',
  '    for (i = 0; i < n; i++) {',
  '      var v = daily[i].tokens;',
  '      var bh = max > 0 ? Math.max(v > 0 ? 1 : 0, Math.round((v / max) * (h - 4))) : 0;',
  '      var x = i * bw;',
  '      out.push(\'<rect x="\' + (x + 0.5).toFixed(2) + \'" y="\' + (h - bh) + \'" width="\' + Math.max(1, bw - 1).toFixed(2) + \'" height="\' + bh + \'" rx="1" fill="currentColor" opacity="\' + (i === n - 1 ? \'0.95\' : \'0.55\') + \'"><title>\' + esc(daily[i].day + ": " + tok(v) + " tokens") + \'</title></rect>\');',
  '    }',
  '    out.push("</svg>");',
  "    return '<div class=\"section\"><div class=\"h\">Last 30 days<span class=\"dim\"> tokens/day</span></div>' + out.join('') + '</div>';",
  '  }',
  '  function table(title, rows) {',
  "    if (!rows || !rows.length) { return '<div class=\"section\"><div class=\"h\">' + esc(title) + '</div><div class=\"dim\">No data yet</div></div>'; }",
  '    var max = rows[0].tokens || 1;',
  '    var body = rows.map(function (r) {',
  "      return '<tr><td class=\"nm\" title=\"' + esc(r.name) + '\">' + esc(r.name) + '</td>' +",
  "        '<td class=\"bar\"><span style=\"width:' + Math.max(2, Math.round((r.tokens * 100) / max)) + '%\"></span></td>' +",
  "        '<td class=\"num\">' + tok(r.tokens) + '</td>' +",
  "        '<td class=\"num\">' + (r.priced ? cost(r.cost) : '<span title=\"No price table entry for this model\">n/a</span>') + '</td></tr>';",
  "    }).join('');",
  "    return '<div class=\"section\"><div class=\"h\">' + esc(title) + '</div><table>' + body + '</table></div>';",
  '  }',
  '  function connections(list) {',
  '    if (!list || !list.length) { return \'<div class="dim">No agents configured</div>\'; }',
  '    return list.map(function (c) {',
  '      return \'<div class="row"><span class="dot \' + (c.connected ? \'on\' : \'off\') + \'"></span><span class="nm">\' + esc(c.name) + \'</span><span class="dim">\' + (c.connected ? \'connected\' : \'offline\') + \' \\u00b7 \' + (c.sessions || 0) + \' session(s)</span></div>\';',
  "    }).join('');",
  '  }',
  '  function sessions(list) {',
  '    if (!list || !list.length) { return \'<div class="dim">No recent sessions</div>\'; }',
  "    return list.map(function (s) {",
  '      return \'<div class="row link" data-agent="\' + esc(s.agentName) + \'" data-session="\' + esc(s.sessionId) + \'" title="\' + esc(s.cwd) + \'"><span class="nm">\' + esc(s.title || s.sessionId) + \'</span><span class="dim">\' + esc(s.agentName) + \'</span></div>\';',
  "    }).join('');",
  '  }',
  '  function render(m) {',
  '    var u = m.usage;',
  "    slot('status').textContent = m.notice ? m.notice : u.scanning ? 'Scanning transcripts\\u2026' : (u.lastError ? 'Scan failed: ' + u.lastError : u.sources.map(function (s) { return s.files + ' file(s)'; }).join(' \\u00b7 '));",
  "    slot('cards').innerHTML = card('Today', u.periods.today) + card('Last 7 days', u.periods.last7d) + card('Last 30 days', u.periods.last30d) +",
  "      '<div class=\"card\"><div class=\"cap\">All time</div><div class=\"big\">' + tok(u.periods.all.tokens) + ' <span class=\"dim\">tokens</span></div><div class=\"dim\">' + u.periods.all.messages + ' assistant messages</div><div class=\"cost\" title=\"' + esc(EST_TIP) + '\">est. ' + cost(u.periods.all.cost) + '</div></div>';",
  "    slot('connections').innerHTML = connections(m.connections);",
  "    slot('sessions').innerHTML = sessions(m.sessions);",
  '    var empty = !u.hasData;',
  "    slot('chart').innerHTML = empty ? '' : chart(u.daily);",
  "    slot('breakdown').innerHTML = empty ? '' : table('Top models (30d)', u.breakdown.last30d.models) + table('Top projects (30d)', u.breakdown.last30d.projects);",
  "    slot('empty').hidden = !empty;",
  "    if (empty) {",
  "      slot('empty').innerHTML = '<div class=\"h\">No transcripts found yet</div><div class=\"dim\">' + (u.scanning ? 'Scanning\\u2026' : 'Checked ' + u.sources.map(function (s) { return esc(s.agent) + ': ' + s.files + ' file(s)'; }).join(', ') + '. Set vac.dashboard.claudeProjectsDir if your transcripts live elsewhere.') + '</div>';",
  '    }',
  "    if (u.unpriced.tokens > 0) { slot('unpriced').textContent = 'Unpriced models: ' + u.unpriced.models.join(', ') + ' (' + tok(u.unpriced.tokens) + ' tokens excluded from est. cost)'; }",
  '  }',
  "  document.addEventListener('click', function (ev) {",
  "    var cmd = ev.target.closest('[data-command]');",
  "    if (cmd) { var id = cmd.getAttribute('data-command'); if (COMMANDS.indexOf(id) >= 0) { api.postMessage({ type: 'command', id: id }); } return; }",
  "    var row = ev.target.closest('[data-session]');",
  "    if (row) { api.postMessage({ type: 'openSession', agentName: row.getAttribute('data-agent'), sessionId: row.getAttribute('data-session') }); }",
  '  });',
  "  window.addEventListener('message', function (ev) { var m = ev.data; if (m && m.type === 'snapshot') { render(m); } });",
  "  document.addEventListener('keydown', function (ev) {",
  "    if (ev.key === 'Enter' && ev.target.classList && ev.target.classList.contains('row')) { ev.target.click(); }",
  '  });',
  "  api.postMessage({ type: 'refresh' });",
  '})();',
].join('\n');

export function renderDashboardHtml(opts: DashboardHtmlOptions): string {
  const csp = [
    "default-src 'none'",
    "img-src " + opts.cspSource + ' data:',
    'style-src ' + opts.cspSource + " 'unsafe-inline'",
    "script-src 'nonce-" + opts.nonce + "'",
  ].join('; ');

  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="UTF-8">',
    '<meta http-equiv="Content-Security-Policy" content="' + csp + '">',
    '<meta name="viewport" content="width=device-width, initial-scale=1.0">',
    '<title>Dashboard</title>',
    '<style>',
    [
      'body { margin: 0; padding: 8px; font-family: var(--vscode-font-family); font-size: var(--vscode-font-size); color: var(--vscode-foreground); background: transparent; }',
      '.actions { display: flex; flex-wrap: wrap; gap: 4px; margin-bottom: 8px; }',
      'button { font: inherit; color: var(--vscode-button-secondaryForeground, var(--vscode-foreground)); background: var(--vscode-button-secondaryBackground, var(--vscode-button-background)); border: 1px solid var(--vscode-panel-border, transparent); border-radius: 3px; padding: 3px 8px; cursor: pointer; }',
      'button:hover { background: var(--vscode-button-secondaryHoverBackground, var(--vscode-button-background)); }',
      'button:focus-visible { outline: 1px solid var(--vscode-focusBorder); outline-offset: 1px; }',
      '#cards { display: grid; grid-template-columns: 1fr 1fr; gap: 6px; }',
      '.card { border: 1px solid var(--vscode-panel-border, var(--vscode-widget-border, transparent)); border-radius: 4px; padding: 6px 7px; background: var(--vscode-editorWidget-background, transparent); min-width: 0; }',
      '.cap, .h { font-size: 11px; text-transform: uppercase; letter-spacing: 0.04em; color: var(--vscode-descriptionForeground); margin-bottom: 3px; }',
      '.h { text-transform: none; letter-spacing: 0; font-size: 12px; }',
      '.big { font-size: 16px; font-weight: 600; white-space: nowrap; }',
      '.dim { color: var(--vscode-descriptionForeground); font-size: 11px; }',
      '.cost { margin-top: 2px; font-size: 12px; }',
      '.section { margin-top: 10px; }',
      'svg { display: block; color: var(--vscode-charts-blue, var(--vscode-foreground)); }',
      'table { width: 100%; border-collapse: collapse; }',
      'td { padding: 2px 0; vertical-align: middle; }',
      'td.nm { max-width: 110px; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }',
      'td.bar span { display: block; height: 6px; background: var(--vscode-charts-green, var(--vscode-foreground)); border-radius: 2px; }',
      'td.num { text-align: right; padding-left: 6px; color: var(--vscode-descriptionForeground); }',
      '.row { display: flex; align-items: center; gap: 5px; padding: 2px 0; min-width: 0; }',
      '.row .nm { overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }',
      '.row.link { cursor: pointer; border-radius: 3px; }',
      '.row.link:hover { background: var(--vscode-list-hoverBackground); }',
      '.dot { width: 7px; height: 7px; border-radius: 50%; flex: none; background: var(--vscode-charts-red, #c33); }',
      '.dot.on { background: var(--vscode-charts-green, #3c3); }',
      '#status { margin-top: 10px; font-size: 11px; color: var(--vscode-descriptionForeground); }',
      '#empty { margin-top: 10px; }',
    ].join('\n'),
    '</style>',
    '</head>',
    '<body>',
    // [CUSTOM-230 行动区只剩两颗文字按钮，各带一条悬停说明。
    // 「打开到编辑区」**不在页面上**：它是视图标题栏里 ↻ 左侧那颗图标（见 DashboardHtml 顶部的
    // 白名单注释），页面里再放一颗就是同一个命令的第二个入口。
    '<div class="actions">',
    '<button data-command="vac.newConversation" title="Start a new conversation (connects an agent first if none is active)">New conversation</button>',
    '<button data-command="vac.connectAgent" title="Connect to an agent (starts its CLI process)">Connect agent</button>',
    '</div>',
    '<div class="section"><div class="h">Connections</div><div id="connections" class="dim">Loading\u2026</div></div>',
    '<div class="section"><div class="h">Usage</div><div id="cards"></div></div>',
    '<div id="chart"></div>',
    '<div id="breakdown"></div>',
    '<div class="section"><div class="h">Recent sessions</div><div id="sessions" class="dim">Loading\u2026</div></div>',
    '<div id="empty" hidden></div>',
    '<div id="unpriced" class="dim"></div>',
    '<div id="status">Loading\u2026</div>',
    '<script nonce="' + opts.nonce + '">',
    CLIENT_SCRIPT,
    '</script>',
    '</body>',
    '</html>',
  ].join('\n');
}
